// Map geometry for the Bierkarte on /wissen/dialekte — run once, output committed.
//
// Beer landscapes, mostly whole states, split where the beer changes inside one: NRW into
// Kölsch (the Ripuarian dialect area), Alt (Lower Rhine) and Westfalen/Ruhr; Bavaria into
// Franken, Oberpfalz and Altbayern along the dialect outlines. Everything is cut from the
// same German-speaking area and drawn with the same projection as the dialect map (both come
// from scripts/generate-dialekte-karte.mjs), so the land, borders and dots line up.
//
// Writes src/data/bier-karte.json: a <path d> and a label position per region, and which
// region each place on the map lies in (for the "Orte" list on a region card).
//
// Same setup as the dialect map:
//   NODE_PATH=/tmp/geo/node_modules ADM1=/tmp/geo/adm1.geojson node scripts/generate-bier-karte.mjs
import fs from "fs";
import { pc, state, union, MASK, CHE_DE, LIE, LUX, AUT, lorraine, ostbelgien, parts, stream, mp, P } from "./generate-dialekte-karte.mjs";

const bier = JSON.parse(fs.readFileSync("src/data/bier.json", "utf8"));
const de = (...names) => union(...names.map((n) => state("DEU:" + n)));

const NRW = de("Nordrhein-Westfalen"), BY = de("Bayern");
const koelsch = pc.intersection(NRW, parts.ripuarisch);
const alt = pc.intersection(NRW, parts.niederrheinisch);
const franken = pc.intersection(BY, union(parts.ostfraenkisch, parts.hessisch, parts.thueringisch, parts.suedfraenkisch));
const oberpfalz = pc.difference(pc.intersection(BY, parts.nordbairisch), franken);

const SHAPES = {
  norden: de("Schleswig-Holstein", "Hamburg", "Bremen", "Niedersachsen", "Mecklenburg-Vorpommern"),
  berlin: de("Berlin", "Brandenburg"),
  koelsch,
  alt,
  westfalen: pc.difference(NRW, koelsch, alt),
  suedwest: de("Hessen", "Rheinland-Pfalz", "Saarland"),
  sachsen: de("Sachsen", "Sachsen-Anhalt"),
  thueringen: de("Thüringen"),
  bawue: de("Baden-Württemberg"),
  franken,
  oberpfalz,
  altbayern: pc.difference(BY, franken, oberpfalz),
  oesterreich: AUT,
  schweiz: union(CHE_DE, LIE),
  suedtirol: state("ITA:Bozen"),
  elsass: union(state("FRA:Bas-Rhin"), state("FRA:Haute-Rhin"), lorraine),
  luxemburg: union(LUX, ostbelgien),
};
for (const r of bier.regions) if (!SHAPES[r.id]) throw new Error("no shape for " + r.id);
for (const id of Object.keys(SHAPES)) if (!bier.regions.some((r) => r.id === id)) throw new Error("no data for " + id);

const shape = Object.fromEntries(Object.entries(SHAPES).map(([id, g]) => [id, pc.intersection(g, MASK)]));

// Point in (multi)polygon, even-odd over all rings.
const inside = ([x, y], g) => {
  let c = false;
  for (const p of g) for (const r of p) for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
    const [xi, yi] = r[i], [xj, yj] = r[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
  }
  return c;
};
const placeRegion = {};
for (const p of bier.places) {
  const r = Object.keys(shape).find((id) => inside(p.at, shape[id]));
  if (r) placeRegion[p.id] = r;
  else console.log("outside every region:", p.id);
}

const out = {
  _comment: "Generated by scripts/generate-bier-karte.mjs from Natural Earth (public domain). Do not edit by hand.",
  regions: Object.fromEntries(bier.regions.map((r) => [r.id, stream(mp(shape[r.id]))])),
  labels: Object.fromEntries(bier.regions.map((r) => [r.id, P(r.label)])),
  placeRegion,
};
fs.writeFileSync("src/data/bier-karte.json", JSON.stringify(out));
console.log("size", (Buffer.byteLength(JSON.stringify(out)) / 1024).toFixed(0) + " KB");
for (const [k, v] of Object.entries(out.regions)) if (!v) console.log("EMPTY", k);
